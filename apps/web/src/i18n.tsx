export interface ServiceDescriptionSource {
  id: string;
  code: string;
  description: string | null;
  descriptionVariants?: LocalizedTextVariants;
}

export function resolveLocalizedValue(canonicalValue: string | null, locale: string, variants?: LocalizedTextVariants): string | null {
  if (canonicalValue === null) return null;
  const variant = variants?.[locale];
  return variant !== undefined && variant.trim().length > 0 ? variant : canonicalValue;
}

